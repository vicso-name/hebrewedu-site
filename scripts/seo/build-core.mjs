#!/usr/bin/env node
// Builds docs/seo/semantic-core.xlsx from docs/seo/core/{keywords,pages,clusters}.csv.
//
// docs/seo/core/*.csv is the single source of truth (see docs/seo/README.md).
// This script ONLY reads those three CSVs — never docs/seo/research/, never
// dist/, never a paid API — and NEVER writes to docs/seo/core/. It validates
// the CSVs and fails loudly on structural problems rather than silently
// building a workbook from broken data.
//
// To change what's in core/, edit the CSVs by hand (or with a provider-batch
// import script) and re-run `npm run seo:build`. To do the one-time legacy
// research -> core/ conversion, see scripts/seo/migrate-legacy.mjs — it is
// not run by this script or by any npm script.
//
// Run: npm run seo:build

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ExcelJS from "exceljs";
import { loadCSV, toObjects } from "./csv.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "../..");
const CORE = path.join(ROOT, "docs/seo/core");

function num(v) {
  if (v === undefined || v === null) return null;
  const s = String(v).trim();
  if (s === "") return null;
  const n = Number(s);
  return Number.isFinite(n) ? n : null;
}

// ---------------------------------------------------------------------------
// 1. Load core/*.csv (the only files this script reads)
// ---------------------------------------------------------------------------

const KEYWORDS_PATH = path.join(CORE, "keywords.csv");
const CLUSTERS_PATH = path.join(CORE, "clusters.csv");
const PAGES_PATH = path.join(CORE, "pages.csv");

for (const [label, p] of [
  ["keywords.csv", KEYWORDS_PATH],
  ["clusters.csv", CLUSTERS_PATH],
  ["pages.csv", PAGES_PATH],
]) {
  if (!fs.existsSync(p)) {
    console.error(
      `ERROR: docs/seo/core/${label} does not exist. core/*.csv is the source of truth and ` +
        `is no longer generated by this script. If this is a fresh checkout with no core/ yet, ` +
        `run \`node scripts/seo/migrate-legacy.mjs\` once to seed it from the legacy research files.`
    );
    process.exit(1);
  }
}

const keywordsCsv = loadCSV(KEYWORDS_PATH, fs);
const clustersCsv = loadCSV(CLUSTERS_PATH, fs);
const pagesCsv = loadCSV(PAGES_PATH, fs);

const keywords = toObjects(keywordsCsv);
const clusters = toObjects(clustersCsv);
const pages = toObjects(pagesCsv);

// ---------------------------------------------------------------------------
// 2. Validation — fail loudly and clearly, write nothing on failure
// ---------------------------------------------------------------------------

const REQUIRED_KEYWORD_COLUMNS = [
  "keyword",
  "market",
  "volume",
  "volume_date",
  "kd",
  "kd_source",
  "intent",
  "cluster_id",
  "is_cluster_primary",
  "target_url",
  "page_role",
  "status",
  "serp_validated",
  "gsc_impr_3m",
  "gsc_pos_3m",
  "rank_baseline_pos",
  "priority_score",
  "source_file",
  "notes",
];
const REQUIRED_CLUSTER_COLUMNS = [
  "cluster_id",
  "name",
  "primary_keyword",
  "total_volume",
  "median_kd",
  "target_url",
  "status",
  "serp_validated",
  "cannibalization_note",
];
const REQUIRED_PAGE_COLUMNS = [
  "url",
  "title",
  "h1",
  "meta_description",
  "primary_cluster",
  "primary_keyword",
  "secondary_keywords",
  "gsc_clicks_3m",
  "gsc_impr_3m",
  "gsc_pos_3m",
  "gsc_clicks_28d",
  "gsc_impr_28d",
  "gsc_pos_28d",
  "gsc_date",
  "status",
];

function intentWeight(intent) {
  if (!intent) return null;
  const s = intent.toLowerCase();
  if (s.includes("commercial") || s.includes("transactional")) return 15;
  if (s.includes("navigational")) return 10;
  if (s.includes("informational")) return 8;
  return 5;
}

// Documented in docs/seo/README.md — keep in sync with that file.
function computePriorityScore({ volume, kd, intent, gscImpr3m, gscPos3m }) {
  const volumeComponent = volume === null ? null : (Math.min(volume, 2000) / 2000) * 50;
  const kdPenalty = kd === null ? null : (kd / 100) * 20;
  const intentComponent = intentWeight(intent);
  const quickWin = gscPos3m !== null && gscPos3m >= 8 && gscPos3m <= 20 && (gscImpr3m || 0) > 0;
  const quickWinBonus = quickWin ? 15 : 0;

  if (volumeComponent === null && intentComponent === null && !quickWin) {
    return null; // empty priority_score
  }
  const score = (volumeComponent || 0) + (intentComponent || 0) + quickWinBonus - (kdPenalty || 0);
  return Math.round(Math.max(score, 0) * 10) / 10;
}

const errors = [];

// 2a. Missing required columns
function checkColumns(label, header, required) {
  const missing = required.filter((c) => !header.includes(c));
  if (missing.length) {
    errors.push(`${label}: missing required column(s): ${missing.join(", ")}`);
  }
}
checkColumns("keywords.csv", keywordsCsv.header, REQUIRED_KEYWORD_COLUMNS);
checkColumns("clusters.csv", clustersCsv.header, REQUIRED_CLUSTER_COLUMNS);
checkColumns("pages.csv", pagesCsv.header, REQUIRED_PAGE_COLUMNS);

// Bail out before any check that assumes these columns exist.
if (errors.length) {
  reportAndExit(errors);
}

// 2b. Duplicate keywords (case-insensitive)
{
  const seen = new Map(); // lowercase keyword -> first row number (1-indexed, header = row 1)
  const dupes = new Map();
  keywords.forEach((r, i) => {
    const k = r.keyword.trim().toLowerCase();
    if (!k) return;
    if (seen.has(k)) {
      if (!dupes.has(k)) dupes.set(k, [seen.get(k)]);
      dupes.get(k).push(i + 2);
    } else {
      seen.set(k, i + 2);
    }
  });
  for (const [k, rowNums] of dupes) {
    errors.push(`keywords.csv: duplicate keyword "${k}" on rows ${rowNums.join(", ")}`);
  }
}

// 2c. Keywords pointing to a cluster_id that does not exist
{
  const clusterIds = new Set(clusters.map((c) => c.cluster_id));
  const missing = new Map(); // cluster_id -> [keywords]
  for (const r of keywords) {
    const cid = r.cluster_id.trim();
    if (cid && !clusterIds.has(cid)) {
      if (!missing.has(cid)) missing.set(cid, []);
      missing.get(cid).push(r.keyword);
    }
  }
  for (const [cid, kws] of missing) {
    errors.push(
      `keywords.csv: cluster_id "${cid}" does not exist in clusters.csv (keywords: ${kws.slice(0, 5).join(", ")}${kws.length > 5 ? `, +${kws.length - 5} more` : ""})`
    );
  }
}

// 2d. A cluster mapped to 2+ target URLs without a cannibalization note
{
  const urlsByCluster = new Map();
  for (const r of keywords) {
    const cid = r.cluster_id.trim();
    const url = r.target_url.trim();
    if (!cid || !url) continue;
    if (!urlsByCluster.has(cid)) urlsByCluster.set(cid, new Set());
    urlsByCluster.get(cid).add(url);
  }
  const clusterNoteById = new Map(clusters.map((c) => [c.cluster_id, c.cannibalization_note.trim()]));
  for (const [cid, urls] of urlsByCluster) {
    if (urls.size > 1 && !clusterNoteById.get(cid)) {
      errors.push(
        `clusters.csv: cluster_id "${cid}" maps to ${urls.size} different target_urls in keywords.csv ` +
          `(${[...urls].join("; ")}) but has no cannibalization_note explaining why. ` +
          `Either fix the target_url(s) in keywords.csv, or document the split in clusters.csv's cannibalization_note column.`
      );
    }
  }
}

// 2e. priority_score not matching the documented formula
{
  const TOLERANCE = 0.05;
  const mismatches = [];
  for (const r of keywords) {
    const expected = computePriorityScore({
      volume: num(r.volume),
      kd: num(r.kd),
      intent: r.intent,
      gscImpr3m: num(r.gsc_impr_3m),
      gscPos3m: num(r.gsc_pos_3m),
    });
    const stored = r.priority_score.trim();
    const storedNum = stored === "" ? null : num(stored);
    const bothEmpty = expected === null && storedNum === null;
    const bothMatch = expected !== null && storedNum !== null && Math.abs(expected - storedNum) <= TOLERANCE;
    if (!bothEmpty && !bothMatch) {
      mismatches.push({ keyword: r.keyword, stored: stored === "" ? "(empty)" : stored, expected: expected === null ? "(empty)" : expected });
    }
  }
  if (mismatches.length) {
    const sample = mismatches
      .slice(0, 8)
      .map((m) => `"${m.keyword}": stored=${m.stored}, formula=${m.expected}`)
      .join("; ");
    errors.push(
      `keywords.csv: priority_score does not match the documented formula (docs/seo/README.md) for ` +
        `${mismatches.length} row(s): ${sample}${mismatches.length > 8 ? `, +${mismatches.length - 8} more` : ""}`
    );
  }
}

if (errors.length) {
  reportAndExit(errors);
}

function reportAndExit(errs) {
  console.error(`seo:build: ${errs.length} validation error(s) in docs/seo/core/ — nothing was written.\n`);
  for (const e of errs) console.error(`  - ${e}`);
  process.exit(1);
}

// ---------------------------------------------------------------------------
// 3. Derived, read-only views for the workbook (no writes to core/)
// ---------------------------------------------------------------------------

const byCluster = new Map();
for (const r of keywords) {
  const cid = r.cluster_id.trim();
  if (!cid) continue;
  if (!byCluster.has(cid)) byCluster.set(cid, []);
  byCluster.get(cid).push(r);
}

// Content plan: unpublished clusters, ranked by the highest priority_score
// among their keywords.
const contentPlan = clusters
  .filter((c) => c.status.trim() !== "published")
  .map((c) => {
    const rows = byCluster.get(c.cluster_id) || [];
    const scores = rows.map((r) => num(r.priority_score)).filter((v) => v !== null);
    const maxScore = scores.length ? Math.max(...scores) : "";
    return {
      cluster_id: c.cluster_id,
      name: c.name,
      primary_keyword: c.primary_keyword,
      target_url: c.target_url,
      status: c.status,
      max_priority_score: maxScore,
      serp_validated: c.serp_validated,
    };
  })
  .sort((a, b) => (b.max_priority_score || 0) - (a.max_priority_score || 0));

// Cannibalization tab: clusters with a recorded cannibalization_note, plus
// an automated exact-keyword/multi-target check (same rule validation
// enforces, surfaced here for visibility — validation already guarantees
// every such case has a note).
const cannibalization = clusters
  .filter((c) => c.cannibalization_note.trim())
  .map((c) => ({
    cluster_id: c.cluster_id,
    name: c.name,
    target_url: c.target_url,
    cannibalization_note: c.cannibalization_note,
  }));

const byKeywordExact = new Map();
for (const r of keywords) {
  const k = r.keyword.trim().toLowerCase();
  if (!r.target_url.trim()) continue;
  if (!byKeywordExact.has(k)) byKeywordExact.set(k, new Set());
  byKeywordExact.get(k).add(r.target_url.trim());
}
const exactConflicts = [];
for (const [k, urls] of byKeywordExact) {
  if (urls.size > 1) exactConflicts.push({ keyword: k, target_urls: [...urls].join("; ") });
}

// Gaps: computed directly from core/*.csv, so this can't go stale against a
// research pipeline this script no longer reads.
const gaps = [];
{
  const blankVolume = keywords.filter((r) => !r.volume.trim()).length;
  const blankKd = keywords.filter((r) => !r.kd.trim()).length;
  const notSerpValidated = keywords.filter((r) => r.serp_validated.trim().toLowerCase() !== "yes").length;
  const candidates = keywords.filter((r) => r.status.trim() === "candidate").length;
  const noRank = keywords.filter((r) => !r.rank_baseline_pos.trim()).length;
  gaps.push(`${blankVolume}/${keywords.length} keywords have no recorded search volume.`);
  gaps.push(`${blankKd}/${keywords.length} keywords have no recorded keyword difficulty.`);
  gaps.push(`${notSerpValidated}/${keywords.length} keywords are not yet SERP-validated (serp_validated != yes).`);
  gaps.push(`${candidates}/${keywords.length} keywords are still status=candidate (not promoted).`);
  gaps.push(`${noRank}/${keywords.length} keywords have no rank_baseline_pos on record.`);
  if (exactConflicts.length) {
    gaps.push(
      `${exactConflicts.length} exact keyword string(s) map to more than one target_url: ${exactConflicts
        .map((c) => c.keyword)
        .join(", ")}.`
    );
  }
}

// ---------------------------------------------------------------------------
// 4. Workbook
// ---------------------------------------------------------------------------

async function buildWorkbook() {
  const wb = new ExcelJS.Workbook();
  wb.created = new Date();

  const readme = wb.addWorksheet("README");
  readme.columns = [{ width: 100 }];
  const readmeLines = [
    "HebrewEdu Semantic Core — generated view",
    `Generated: ${new Date().toISOString().slice(0, 10)} by scripts/seo/build-core.mjs (npm run seo:build)`,
    "",
    "Source of truth for editing: docs/seo/core/keywords.csv, clusters.csv, pages.csv.",
    "This workbook is a READ-ONLY generated view, built ONLY from those three CSVs. Do not hand-edit it, and do not edit docs/seo/research/ expecting it to flow in — edit the core CSVs directly and re-run `npm run seo:build`.",
    "",
    "priority_score formula (0 pts floor, no ceiling beyond component caps):",
    "  volume_component = min(volume, 2000) / 2000 * 50        (0 if volume unknown — never scored as 0 volume)",
    "  intent_component = 15 commercial/transactional, 10 navigational, 8 informational, 5 other/unknown",
    "  quick_win_bonus  = +15 if gsc_pos_3m is between 8 and 20 AND gsc_impr_3m > 0",
    "  kd_penalty       = (kd / 100) * 20                        (0 if KD unknown)",
    "  priority_score   = volume_component + intent_component + quick_win_bonus - kd_penalty",
    "Rows with neither volume, intent, nor a quick-win signal get an EMPTY priority_score (confidence: none) rather than a numeric 0 — null data lowers confidence, it never counts as zero demand.",
    "`npm run seo:build` validates every row against this formula and refuses to build if any row disagrees.",
    "",
    "Tabs: Clusters, Keywords, Pages, Content plan (unpublished clusters by priority), Cannibalization, Gaps.",
  ];
  readmeLines.forEach((l) => readme.addRow([l]));

  function addTable(name, columns, rows) {
    const ws = wb.addWorksheet(name);
    ws.columns = columns.map((c) => ({ header: c, key: c, width: Math.max(14, Math.min(40, c.length + 4)) }));
    ws.addRows(rows);
    ws.getRow(1).font = { bold: true };
    ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: columns.length } };
  }

  addTable("Clusters", REQUIRED_CLUSTER_COLUMNS, clusters);
  addTable("Keywords", REQUIRED_KEYWORD_COLUMNS, keywords);
  addTable("Pages", REQUIRED_PAGE_COLUMNS, pages);
  addTable(
    "Content plan",
    ["cluster_id", "name", "primary_keyword", "target_url", "status", "max_priority_score", "serp_validated"],
    contentPlan
  );
  addTable(
    "Cannibalization",
    ["cluster_id", "name", "target_url", "cannibalization_note"],
    cannibalization
  );
  const gapsWs = wb.addWorksheet("Gaps");
  gapsWs.columns = [{ width: 110 }];
  gaps.forEach((g) => gapsWs.addRow([g]));

  await wb.xlsx.writeFile(path.join(ROOT, "docs/seo/semantic-core.xlsx"));
}

await buildWorkbook();

// ---------------------------------------------------------------------------
// 5. Console summary
// ---------------------------------------------------------------------------

console.log(`keywords.csv: ${keywords.length} rows (read-only)`);
console.log(`clusters.csv: ${clusters.length} clusters (read-only)`);
console.log(`pages.csv: ${pages.length} rows (read-only)`);
console.log(`cannibalization entries: ${cannibalization.length}`);
console.log(`content plan entries: ${contentPlan.length}`);
console.log("docs/seo/semantic-core.xlsx written");
